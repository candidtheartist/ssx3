"""Build the native game functions listed in native_functions.txt into one object.

    gen_native.py <repo root> <work dir> <output .o>

Each listed unit of the decomp is compiled for the 32-bit host, with an entry
point per swapped function (native_abi.h). Symbols the units leave undefined
resolve to the game's own EE addresses (EE memory sits at those addresses in
the PC process), or to the host C library, or to a stub that stops the game if
anything ever calls it (it is code that stays recompiled, which native code
does not call yet). Everything is linked into one relocatable object whose only
global symbols are the table and its count, so no game symbol can clash with
the runtime's or the C library's, and static constructors are dropped: the
game's globals live in EE memory, not in the host copies these units define.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from native_flags import HOST_CXXFLAGS  # noqa: E402

# EE functions whose host stand-in has a different name, with its C signature.
ALIASES = {
    "memmove": ("void *{n}(void *d, const void *s, unsigned int len)", "return __builtin_memmove(d, s, len);"),
    "strlen": ("unsigned int {n}(const char *s)", "return __builtin_strlen(s);"),
    "strchr": ("char *{n}(const char *s, int c)", "return __builtin_strchr(s, c);"),
    "strcmp": ("int {n}(const char *a, const char *b)", "return __builtin_strcmp(a, b);"),
    "strcpy": ("char *{n}(char *d, const char *s)", "return __builtin_strcpy(d, s);"),
    "strncpy": ("char *{n}(char *d, const char *s, unsigned int len)", "return __builtin_strncpy(d, s, len);"),
    "strncmp": ("int {n}(const char *a, const char *b, unsigned int len)", "return __builtin_strncmp(a, b, len);"),
    "memset": ("void *{n}(void *d, int c, unsigned int len)", "return __builtin_memset(d, c, len);"),
}


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        sys.stderr.write(" ".join(cmd) + "\n" + r.stdout + r.stderr)
        sys.exit(1)
    return r.stdout


def main():
    root, work, output = sys.argv[1:4]
    os.makedirs(work, exist_ok=True)
    funcs = {}
    for line in open(os.path.join(HERE, "native_functions.txt")):
        if line.strip() and not line.startswith("#"):
            unit, addr, name = line.split()
            funcs.setdefault(unit, []).append((int(addr, 16), name))
    symbols = {}
    for line in open(os.path.join(HERE, "native_symbols.txt")):
        if line.strip() and not line.startswith("#"):
            sym, kind, value = line.split()
            symbols[sym] = (kind, value)

    objs = []
    table = []
    for unit, entries in sorted(funcs.items()):
        stem = unit.replace("/", "_").replace(".", "_")
        wrapper = os.path.join(work, stem + ".cpp")
        with open(wrapper, "w") as f:
            f.write(f'#include "{os.path.join(root, unit)}"\n#include "native_abi.h"\n')
            for addr, name in entries:
                f.write(f"SSX3_NATIVE({addr:08X}, {name})\n")
                table.append(addr)
        obj = wrapper[:-4] + ".o"
        run(["g++"] + HOST_CXXFLAGS + ["-I" + HERE, "-I" + os.path.join(root, "include"),
                                       "-I" + os.path.join(root, "src"), "-c", wrapper, "-o", obj])
        objs.append(obj)

    # what the units still need from outside
    undefined = set()
    defined = set()
    for obj in objs:
        for line in run(["nm", obj]).splitlines():
            parts = line.split()
            if len(parts) == 2 and parts[0] == "U":
                undefined.add(parts[1])
            elif len(parts) == 3 and parts[1] in "TtDdBbRrWVv":
                defined.add(parts[2])
    undefined -= defined

    glue = os.path.join(work, "native_glue.cpp")
    with open(glue, "w") as f:
        f.write("// Generated by gen_native.py.\n")
        f.write("struct Ssx3NativeFrame;\n")
        f.write('extern "C" void ssx3NativeUnreachable(const char *name);\n')
        f.write("struct Ssx3NativeEntry { unsigned int address; void (*entry)(Ssx3NativeFrame *); };\n")
        for a in table:
            f.write(f'extern "C" void ssx3n_{a:08X}(Ssx3NativeFrame *);\n')
        f.write('extern "C" const Ssx3NativeEntry g_ssx3NativeTable[] = {\n')
        for a in table:
            f.write(f"    {{0x{a:08X}u, ssx3n_{a:08X}}},\n")
        f.write("};\n")
        f.write(f'extern "C" const unsigned int g_ssx3NativeCount = {len(table)}u;\n')
        n = 0
        for sym in sorted(undefined):
            if sym.startswith("__x86.") or sym == "_GLOBAL_OFFSET_TABLE_":
                continue
            kind, value = symbols.get(sym, ("libc", sym))
            if kind == "data":
                f.write(f'asm(".globl {sym}\\n.set {sym}, {value}");\n')
            elif kind == "libc" and value != sym:
                sig = ALIASES[value][0].format(n=f"ssx3a_{n}")
                f.write(f'extern "C" {sig} __asm__("{sym}");\n')
                f.write(f'extern "C" {sig} {{ {ALIASES[value][1]} }}\n')
                n += 1
            elif kind in ("code", "missing"):
                f.write(f'extern "C" void ssx3s_{n}() __asm__("{sym}");\n')
                f.write(f'extern "C" void ssx3s_{n}() {{ ssx3NativeUnreachable("{sym}"); }}\n')
                n += 1
            # libc under its own name: the host C library provides it
    glue_obj = glue[:-4] + ".o"
    run(["g++"] + HOST_CXXFLAGS + ["-c", glue, "-o", glue_obj])

    combined = os.path.join(work, "native_combined.o")
    run(["ld", "-m", "elf_i386", "-r", "--force-group-allocation", "-o", combined] + objs + [glue_obj])
    run(["objcopy", "--remove-section=.init_array", "--remove-section=.ctors", "--remove-section=.fini_array",
         "--remove-section=.dtors",
         "-G", "g_ssx3NativeTable", "-G", "g_ssx3NativeCount", "-G", "ssx3NativeUnreachable",
         combined, output])
    print(f"native: {len(table)} functions from {len(objs)} units -> {output}")


if __name__ == "__main__":
    main()
